import { TEST_DATA_DIR, establishFixtureAccount } from "./test-env.js";
import { before, after, it } from "node:test";
import assert from "node:assert/strict";
import { randomBytes } from "node:crypto";
import { rmSync } from "node:fs";
import { resolve, sep } from "node:path";
import { tmpdir } from "node:os";
import type { Server } from "node:http";
import { createApp } from "./app.js";
import { getStore } from "./storage.js";
let server: Server, base = "", main = "", employee = "";
const draft = { platform: "android", versionName: "2.0.0", buildNumber: 20, notes: "A tested Android release", downloadUrl: "https://releases.example.test/stocrant-20.apk", sha256: "a".repeat(64) };
const call = (path: string, body?: unknown, cookie = main) => fetch(base + "/api" + path, { method: body ? "POST" : "GET", headers: { Cookie: cookie, ...(body ? { "Content-Type": "application/json" } : {}) }, ...(body ? { body: JSON.stringify(body) } : {}) });
before(async () => {
  server = createApp().listen(0, "127.0.0.1"); await new Promise<void>(done => server.once("listening", done));
  base = `http://127.0.0.1:${(server.address() as { port: number }).port}`;
  const password = randomBytes(24).toString("hex");
  const setup = await call("/auth/setup", { name: "Release owner", email: "owner@releases.test", password, setupKey: "local-setup" }); assert.equal(setup.status, 201); main = setup.headers.get("set-cookie")!.split(";")[0];
  const user = await call("/workspace/access/users", { name: "Release user", email: "user@releases.test", password, roleId: "role-employee", organizationIds: ["company-primary"] }); assert.equal(user.status, 201, await user.clone().text());
  await establishFixtureAccount("user@releases.test");
  const login = await call("/auth/login", { email: "user@releases.test", password }, ""); assert.equal(login.status, 200); employee = login.headers.get("set-cookie")!.split(";")[0];
});
after(async () => { server.closeAllConnections(); await new Promise<void>(done => server.close(() => done())); const target = resolve(TEST_DATA_DIR); assert.ok(target.startsWith(resolve(tmpdir()) + sep) && target.includes("stocrant-test-data-")); rmSync(target, { recursive: true, force: true }); });
it("reveals downloads only after Super Admin approval and revokes old notification actions", async () => {
  const path = "/workspace/app-releases";
  assert.equal((await call(path + "/available", undefined, "")).status, 401);
  assert.equal((await call(path, draft, employee)).status, 403);
  assert.equal((await call(path, undefined, employee)).status, 403);
  for (const downloadUrl of ["invalid", "http://example.test/a.apk", "https://name:secret@example.test/a.apk", "https://localhost/a.apk"]) assert.equal((await call(path, { ...draft, downloadUrl })).status, 400);
  const create = await call(path, draft); assert.equal(create.status, 201); const release = (await create.json() as any).item;
  assert.deepEqual((await (await call(path + "/available", undefined, employee)).json() as any).items, []);
  assert.equal((await call(path, draft)).status, 409);
  assert.equal((await call(`${path}/${release.id}/approve`, { version: 1 }, employee)).status, 403);
  assert.equal((await call(`${path}/${release.id}/approve`, { version: 1 })).status, 200);
  const available = (await (await call(path + "/available", undefined, employee)).json() as any).items;
  assert.equal(available[0].versionName, "2.0.0"); assert.equal(available[0].downloadUrl, draft.downloadUrl); assert.equal(available[0].createdBy, undefined);
  const notifications = (await (await call("/notifications", undefined, employee)).json() as any).items;
  const notice = notifications.find((row: any) => row.target === `app-release:${release.id}`); assert.ok(notice); assert.equal((await (await call(`/notifications/${notice.id}`, undefined, employee)).json() as any).link.to, "/app-update");
  assert.equal((await call(`${path}/${release.id}/approve`, { version: 1 })).status, 409);
  const stored = getStore().collections.notifications as any[];
  assert.equal(stored.filter(row => row.userId === notice.userId && row.target === notice.target).length, 1);
  assert.equal((await call(`${path}/${release.id}/withdraw`, { version: 2 })).status, 200);
  assert.deepEqual((await (await call(path + "/available", undefined, employee)).json() as any).items, []);
  const withdrawn = await (await call(`/notifications/${notice.id}`, undefined, employee)).json() as any; assert.equal(withdrawn.link, undefined);
  const next = await call(path, { ...draft, versionName: "2.1.0", buildNumber: 21 }); const nextRelease = (await next.json() as any).item;
  assert.equal((await call(`${path}/${nextRelease.id}/approve`, { version: 1 })).status, 200);
  const older = await call(path, { ...draft, versionName: "1.0.0", buildNumber: 19 }); const olderRelease = (await older.json() as any).item;
  assert.equal((await call(`${path}/${olderRelease.id}/approve`, { version: 1 })).status, 409);
  assert.equal((await call("/collections/appReleases", undefined, employee)).status, 404);
});
